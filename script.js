let sortableInstance = null;

/**
 * Initialize drag & drop cho timeline
 */
function initDragAndDrop() {
    const timeline = document.getElementById('routeTimeline');
    if (!timeline) return;

    // Destroy existing instance if any
    if (sortableInstance) {
        sortableInstance.destroy();
    }

    // Create new Sortable instance
    sortableInstance = Sortable.create(timeline, {
        animation: 200,           // Animation duration (ms)
        easing: "cubic-bezier(1, 0, 0, 1)",
        handle: '.drag-handle',   // Drag handle selector
        draggable: '.timeline-item', // Draggable items
        ghostClass: 'sortable-ghost',
        chosenClass: 'sortable-chosen',
        dragClass: 'sortable-drag',

        // Event khi bắt đầu drag
        onStart: function (evt) {
            console.log('🖐️ Start dragging item:', evt.oldIndex);
        },

        // Event khi kết thúc drag (thả)
        onEnd: function (evt) {
            const oldIndex = evt.oldIndex;
            const newIndex = evt.newIndex;

            console.log(`📍 Moved from index ${oldIndex} to ${newIndex}`);

            // Update data model
            const movedStop = routeData.stops.splice(oldIndex, 1)[0];
            routeData.stops.splice(newIndex, 0, movedStop);

            // Rebuild sub-routes với thứ tự mới
            rebuildSubRoutes();

            // Re-render timeline
            renderTimeline();

            // Re-init drag & drop
            initDragAndDrop();
        }
    });

    console.log('✅ Drag & Drop initialized');
}

