/**
 * Update actual distance khi user thay đổi
 */
function updateActualDistance(subRouteId, newValue) {
    const subRoute = routeData.subRoutes.find(sr => sr.id === subRouteId);
    if (subRoute) {
        subRoute.actualDistance = parseFloat(newValue) || 0;
        updateStats();
        console.log(`✅ Updated ${subRouteId} actual distance to ${newValue} km`);
    }
}

