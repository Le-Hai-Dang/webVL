/**
 * Delete stop và rebuild sub-routes
 */
function deleteStop(stopId) {
    const stopIndex = routeData.stops.findIndex(s => s.id === stopId);
    if (stopIndex === -1) return;

    const stop = routeData.stops[stopIndex];

    if (!confirm(`Xóa điểm dừng: ${stop.fullAddress}?`)) {
        return;
    }

    // Remove stop
    routeData.stops.splice(stopIndex, 1);

    // Rebuild sub-routes
    rebuildSubRoutes();

    // Re-render
    renderTimeline();

    console.log(`🗑️ Deleted stop: ${stopId}`);
}

