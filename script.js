/**
 * Render toàn bộ timeline với stops và sub-routes
 */
function renderTimeline() {
    const timeline = document.getElementById('routeTimeline');
    if (!timeline) return;

    timeline.innerHTML = '';

    // Render từng stop và sub-route sau nó
    routeData.stops.forEach((stop, index) => {
        const timelineItem = createTimelineItem(stop, index);
        timeline.appendChild(timelineItem);
    });

    // Update summary counts
    updateSummary();

    // Update stats
    updateStats();
}

/**
 * Tạo 1 timeline item (bao gồm stop row + sub-route nếu có)
 */
function createTimelineItem(stop, index) {
    const item = document.createElement('div');
    item.className = 'timeline-item';
    item.dataset.stopId = stop.id;

    // Create stop row
    const stopRow = createStopRow(stop, index);
    item.appendChild(stopRow);

    // Create sub-route (nếu không phải stop cuối cùng)
    if (index < routeData.stops.length - 1) {
        const nextStop = routeData.stops[index + 1];
        const subRoute = routeData.subRoutes.find(
            sr => sr.fromStopId === stop.id && sr.toStopId === nextStop.id
        );

        if (subRoute) {
            const subRouteElement = createSubRoute(subRoute, stop, nextStop);
            item.appendChild(subRouteElement);
        }
    }

    return item;
}

/**
 * Tạo stop row (draggable)
 */
function createStopRow(stop, index) {
    const row = document.createElement('div');
    row.className = 'stop-row';
    row.dataset.stopId = stop.id;

    // Marker content: Số cho stops thường, Icon cho return
    let markerContent;
    if (stop.type === 'return') {
        // Icon quay về (return arrow)
        markerContent = `
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" style="width: 20px; height: 20px;">
                <polyline points="1 4 1 10 7 10"></polyline>
                <path d="M3.51 15a9 9 0 1 0 2.13-9.36L1 10"></path>
            </svg>
        `;
    } else {
        // Số thứ tự
        markerContent = index + 1;
    }

    // Note cho return stop
    let addressClass = 'stop-address';
    if (stop.type === 'return') {
        addressClass += ' return-note';
    } else if (stop.address) {
        // Nếu có địa chỉ (đã nhập) -> màu đen
        addressClass += ' filled';
    }

    const addressDisplay = `<div class="${addressClass}">${stop.fullAddress}</div>`;

    row.innerHTML = `
        <!-- Drag Handle -->
        <div class="drag-handle" style="${stop.type === 'return' ? 'cursor: default;' : ''}">
            ${stop.type !== 'return' ? `
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
                <line x1="9" y1="5" x2="9" y2="19"></line>
                <line x1="15" y1="5" x2="15" y2="19"></line>
            </svg>
            ` : ''}
        </div>
        
        <!-- Stop Marker -->
        <div class="stop-marker">
            ${markerContent}
        </div>
        
        <!-- Stop Info -->
        <div class="stop-info">
            <div class="stop-label">${stop.label}</div>
            ${addressDisplay}
        </div>
        
        <!-- Stop Actions -->
        <div class="stop-actions">
            ${stop.editable !== false ? `
            <button class="stop-action-btn edit" onclick="editStop('${stop.id}')">
                <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
                    <path d="M11 4H4a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7"></path>
                    <path d="M18.5 2.5a2.121 2.121 0 0 1 3 3L12 15l-4 1 1-4 9.5-9.5z"></path>
                </svg>
            </button>
            ` : ''}
            ${!stop.required ? `
            <button class="stop-action-btn delete" onclick="deleteStop('${stop.id}')" title="Xóa điểm dừng">
                <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
                    <line x1="18" y1="6" x2="6" y2="18"></line>
                    <line x1="6" y1="6" x2="18" y2="18"></line>
                </svg>
            </button>
            ` : ''}
        </div>
    `;

    return row;
}

/**
 * Tạo sub-route element giữa 2 stops
 */
function createSubRoute(subRoute, fromStop, toStop) {
    const div = document.createElement('div');
    div.className = 'sub-route';
    div.dataset.subrouteId = subRoute.id;

    div.innerHTML = `
        <!-- Sub-route Content -->
        <div class="sub-route-content">
            <div class="sub-route-label">TUYẾN CON ${subRoute.id.replace('subroute-', '')}</div>
            
            <div class="sub-route-info">
                <!-- Distance Info -->
                <div class="sub-route-distance">
                    <div class="distance-item estimated">
                        <span>Ước lượng:</span>
                        <span class="distance-value">${subRoute.estimatedDistance} km</span>
                    </div>
                    
                    <span style="color: #ddd;">|</span>
                    
                    <div class="distance-item actual">
                        <span>Thực tế:</span>
                        <input 
                            type="number" 
                            class="distance-input" 
                            value="${subRoute.actualDistance}"
                            min="0"
                            step="0.1"
                            data-subroute-id="${subRoute.id}"
                            onchange="updateActualDistance('${subRoute.id}', this.value)"
                        />
                        <span>km</span>
                    </div>
                </div>
            </div>
        </div>
    `;

    return div;
}

/**
 * Update summary (số điểm dừng, số tuyến con)
 * Note: "Quay về" KHÔNG tính vào số điểm
 */
function updateSummary() {
    const stopsCount = document.getElementById('stopsCount');
    const subRoutesCount = document.getElementById('subRoutesCount');

    if (stopsCount) {
        // Chỉ đếm stops thật (không tính return)
        const actualStops = routeData.stops.filter(s => s.type !== 'return');
        stopsCount.textContent = `${actualStops.length} điểm`;
    }

    if (subRoutesCount) {
        subRoutesCount.textContent = `${routeData.subRoutes.length} tuyến con`;
    }
}

/**
 * Update stats (tổng ước lượng, tổng thực tế, chênh lệch)
 */
function updateStats() {
    const totalEstimated = calculateTotalDistance(routeData.subRoutes, 'estimatedDistance');
    const totalActual = calculateTotalDistance(routeData.subRoutes, 'actualDistance');
    const difference = calculateDifference(totalActual, totalEstimated);

    const estimatedEl = document.getElementById('totalEstimated');
    const actualEl = document.getElementById('totalActual');
    const differenceEl = document.getElementById('totalDifference');

    if (estimatedEl) {
        estimatedEl.textContent = `${totalEstimated} km`;
    }

    if (actualEl) {
        actualEl.textContent = `${totalActual} km`;
    }

    if (differenceEl) {
        differenceEl.textContent = difference.text;
        // Update class based on positive/negative
        differenceEl.classList.toggle('positive', difference.value < 0);
    }
}

