/**
 * Rebuild sub-routes sau khi thay đổi thứ tự hoặc xóa/thêm stops
 */
function rebuildSubRoutes() {
    const newSubRoutes = [];

    for (let i = 0; i < routeData.stops.length - 1; i++) {
        const fromStop = routeData.stops[i];
        const toStop = routeData.stops[i + 1];

        // Tìm sub-route cũ (nếu có) để giữ lại actual distance
        const existingSubRoute = routeData.subRoutes.find(
            sr => sr.fromStopId === fromStop.id && sr.toStopId === toStop.id
        );

        if (existingSubRoute) {
            // Giữ lại sub-route cũ
            newSubRoutes.push(existingSubRoute);
        } else {
            // Tạo sub-route mới với ước lượng mặc định
            newSubRoutes.push({
                id: generateSubRouteId(),
                fromStopId: fromStop.id,
                toStopId: toStop.id,
                estimatedDistance: 10, // Default - có thể call Google Maps API sau
                actualDistance: 10,
                estimatedTime: 15
            });
        }
    }

    routeData.subRoutes = newSubRoutes;
    console.log('🔄 Rebuilt sub-routes:', newSubRoutes.length);
}

